#!/usr/bin/env bash
set -euo pipefail

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
BUILD_DIR="${REPO_ROOT}/build-deb"

# Extract version from CASTER_VERSION, GITHUB_REF_NAME, git tag, or VERSION file fallback
FALLBACK_VER="$(cat "${REPO_ROOT}/VERSION" 2>/dev/null || echo "0.0.0")"
VERSION="${CASTER_VERSION:-}"
if [ -z "${VERSION}" ]; then
    if [ "${GITHUB_REF_TYPE:-}" = "tag" ] && [ -n "${GITHUB_REF_NAME:-}" ]; then
        VERSION="${GITHUB_REF_NAME#v}"
    else
        TAG_DESC="$(git describe --tags --always --dirty 2>/dev/null || echo "")"
        if [ -n "${TAG_DESC}" ]; then
            VERSION="${TAG_DESC#v}"
        else
            VERSION="${FALLBACK_VER}"
        fi
    fi
fi
export VERSION

echo "Building CasterSoundboard Debian package version: ${VERSION}"

mkdir -p "${BUILD_DIR}"

cmake -B "${BUILD_DIR}" -S "${REPO_ROOT}" \
    -DCMAKE_BUILD_TYPE=Release \
    -DCMAKE_INSTALL_PREFIX=/usr \
    -DCASTER_VERSION="${VERSION}"

cmake --build "${BUILD_DIR}" -j"$(nproc)"

cpack --config "${BUILD_DIR}/CPackConfig.cmake" -G DEB -B "${BUILD_DIR}"

shopt -s nullglob
deb_files=( "${BUILD_DIR}"/*.deb )
if [ ${#deb_files[@]} -gt 0 ]; then
    for deb in "${deb_files[@]}"; do
        dest="${REPO_ROOT}/$(basename "${deb}")"
        mv -f "${deb}" "${dest}"
        echo "Debian package generated: ${dest}"
    done
else
    echo "Error: No .deb package was generated by CPack" >&2
    exit 1
fi
