#!/usr/bin/env bash
set -euo pipefail

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
SPEC_FILE="${REPO_ROOT}/dist/rpm/castersoundboard.spec"
BUILD_DIR="${REPO_ROOT}/build-srpm"

# Extract version from CASTER_VERSION, GITHUB_REF_NAME, git tag, or VERSION file fallback
FALLBACK_VER="$(cat "${REPO_ROOT}/VERSION" 2>/dev/null || echo "0.0.0")"
VERSION="${CASTER_VERSION:-}"
if [ -z "${VERSION}" ]; then
    if [ "${GITHUB_REF_TYPE:-}" = "tag" ] && [ -n "${GITHUB_REF_NAME:-}" ]; then
        VERSION="${GITHUB_REF_NAME#v}"
    else
        TAG_DESC="$(git describe --tags --always --dirty 2>/dev/null || echo "")"
        if [ -n "${TAG_DESC}" ]; then
            VERSION="${TAG_DESC#v}"
        else
            VERSION="${FALLBACK_VER}"
        fi
    fi
fi
RPM_VERSION="$(echo "${VERSION}" | tr '-' '_')"

echo "Building CasterSoundboard Source RPM (SRPM) version: ${RPM_VERSION}"

mkdir -p "${BUILD_DIR}/SOURCES" "${BUILD_DIR}/SPECS" "${BUILD_DIR}/SRPMS"

# Create source tarball
git -C "${REPO_ROOT}" archive --format=tar.gz --prefix="CasterSoundboard-${RPM_VERSION}/" -o "${BUILD_DIR}/SOURCES/CasterSoundboard-${RPM_VERSION}.tar.gz" HEAD

# Copy and update spec file version
sed -e "s/^Version:.*/Version:        ${RPM_VERSION}/" "${SPEC_FILE}" > "${BUILD_DIR}/SPECS/castersoundboard.spec"

rpmbuild -bs \
    --define "_topdir ${BUILD_DIR}" \
    "${BUILD_DIR}/SPECS/castersoundboard.spec"

shopt -s nullglob
srpm_files=( "${BUILD_DIR}/SRPMS"/*.src.rpm )
if [ ${#srpm_files[@]} -gt 0 ]; then
    for srpm in "${srpm_files[@]}"; do
        dest="${REPO_ROOT}/$(basename "${srpm}")"
        mv -f "${srpm}" "${dest}"
        echo "Source RPM generated: ${dest}"
    done
else
    echo "Error: No .src.rpm package was generated by rpmbuild" >&2
    exit 1
fi
