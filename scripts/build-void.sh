#!/usr/bin/env bash
set -euo pipefail

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
BUILD_DIR="${REPO_ROOT}/build-void"
TEMPLATE_FILE="${REPO_ROOT}/dist/void/template"

# Extract version from CASTER_VERSION, GITHUB_REF_NAME, git tag, or VERSION file fallback
FALLBACK_VER="$(cat "${REPO_ROOT}/VERSION" 2>/dev/null || echo "0.0.0")"
VERSION="${CASTER_VERSION:-}"
if [ -z "${VERSION}" ]; then
    if [ "${GITHUB_REF_TYPE:-}" = "tag" ] && [ -n "${GITHUB_REF_NAME:-}" ]; then
        VERSION="${GITHUB_REF_NAME#v}"
    else
        TAG_DESC="$(git describe --tags --always --dirty 2>/dev/null || echo "")"
        if [ -n "${TAG_DESC}" ]; then
            VERSION="${TAG_DESC#v}"
        else
            VERSION="${FALLBACK_VER}"
        fi
    fi
fi
# Void Linux xbps-src versions can only contain digits, dots, and letters (no hyphens or underscores)
VOID_VERSION="$(echo "${VERSION}" | sed 's/[-_].*//')"

echo "Building CasterSoundboard Void Linux (XBPS) package version: ${VOID_VERSION}"

mkdir -p "${BUILD_DIR}"
cd "${BUILD_DIR}"

if [ ! -d "void-packages" ]; then
    echo "Cloning void-packages tree..."
    git clone --depth=1 https://github.com/void-linux/void-packages.git
fi

cd void-packages

# Set up package template
mkdir -p srcpkgs/castersoundboard
cp -f "${TEMPLATE_FILE}" srcpkgs/castersoundboard/template

# Pre-generate source tarball so xbps-src can build from local checkout or unreleased commits
SOURCE_DIR="hostdir/sources/castersoundboard-${VOID_VERSION}"
mkdir -p "${SOURCE_DIR}"
TARBALL_PATH="${SOURCE_DIR}/v${VOID_VERSION}.tar.gz"

echo "Creating source archive: ${TARBALL_PATH}..."
if command -v git >/dev/null 2>&1 && [ -d "${REPO_ROOT}/.git" ]; then
    git -C "${REPO_ROOT}" archive --format=tar.gz --prefix="CasterSoundboard-${VOID_VERSION}/" -o "${BUILD_DIR}/void-packages/${TARBALL_PATH}" HEAD
else
    tar --exclude-vcs --exclude='./build*' --exclude='./result' \
        -czf "${BUILD_DIR}/void-packages/${TARBALL_PATH}" \
        -C "${REPO_ROOT}" \
        --transform "s,^\.,CasterSoundboard-${VOID_VERSION}," .
fi

TAR_SHA256="$(sha256sum "${TARBALL_PATH}" | awk '{print $1}')"

# Update template version and checksum dynamically
sed -i -e "s/^version=.*/version=${VOID_VERSION}/" srcpkgs/castersoundboard/template
sed -i -e "s/^checksum=.*/checksum=${TAR_SHA256}/" srcpkgs/castersoundboard/template

# Configure xbps-src for container execution without namespaces
mkdir -p etc
cat << 'EOF' >> etc/conf
XBPS_CHROOT_CMD=ethereal
XBPS_ALLOW_CHROOT_BREAKOUT=yes
EOF

echo "Initializing xbps-src binary-bootstrap..."
./xbps-src binary-bootstrap

echo "Building castersoundboard package via xbps-src..."
./xbps-src pkg castersoundboard

shopt -s nullglob
xbps_files=( hostdir/binpkgs/castersoundboard-*.xbps hostdir/binpkgs/*/castersoundboard-*.xbps )
if [ ${#xbps_files[@]} -gt 0 ]; then
    for pkg in "${xbps_files[@]}"; do
        dest="${REPO_ROOT}/$(basename "${pkg}")"
        cp -f "${pkg}" "${dest}"
        echo "XBPS package generated: ${dest}"
    done
else
    echo "Error: No .xbps package was generated by xbps-src" >&2
    exit 1
fi
