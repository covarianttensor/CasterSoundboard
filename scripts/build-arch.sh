#!/usr/bin/env bash
set -euo pipefail

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
BUILD_DIR="${REPO_ROOT}/build-arch"

# Extract version from CASTER_VERSION, GITHUB_REF_NAME, git tag, or VERSION file fallback
FALLBACK_VER="$(cat "${REPO_ROOT}/VERSION" 2>/dev/null || echo "0.0.0")"
VERSION="${CASTER_VERSION:-}"
if [ -z "${VERSION}" ]; then
    if [ "${GITHUB_REF_TYPE:-}" = "tag" ] && [ -n "${GITHUB_REF_NAME:-}" ]; then
        VERSION="${GITHUB_REF_NAME#v}"
    else
        TAG_DESC="$(git describe --tags --always --dirty 2>/dev/null || echo "")"
        if [ -n "${TAG_DESC}" ]; then
            VERSION="${TAG_DESC#v}"
        else
            VERSION="${FALLBACK_VER}"
        fi
    fi
fi
ARCH_VERSION="$(echo "${VERSION}" | tr '-' '_')"

echo "Building CasterSoundboard Arch Linux package version: ${ARCH_VERSION}"

if ! command -v makepkg >/dev/null 2>&1; then
    echo "Error: makepkg is not installed on this host." >&2
    echo "This script must be run on an Arch-based system or in an archlinux container." >&2
    exit 1
fi

rm -rf "${BUILD_DIR}"
mkdir -p "${BUILD_DIR}"
cd "${BUILD_DIR}"

# Create source tarball
TARBALL="castersoundboard-${ARCH_VERSION}.tar.gz"
if command -v git >/dev/null 2>&1 && [ -d "${REPO_ROOT}/.git" ]; then
    git -C "${REPO_ROOT}" archive --format=tar.gz --prefix="castersoundboard-${ARCH_VERSION}/" -o "${BUILD_DIR}/${TARBALL}" HEAD
else
    tar --exclude-vcs --exclude='./build*' --exclude='./result' \
        -czf "${BUILD_DIR}/${TARBALL}" \
        -C "${REPO_ROOT}" \
        --transform "s,^\.,castersoundboard-${ARCH_VERSION}," .
fi

TAR_SHA256="$(sha256sum "${TARBALL}" | awk '{print $1}')"

# Generate PKGBUILD
cat <<EOF > PKGBUILD
# Maintainer: Oscar Cerna <covarianttensor@gmail.com>
pkgname=castersoundboard
pkgver=${ARCH_VERSION}
pkgrel=1
pkgdesc="Touch-first live soundboard and audio routing tool for Linux"
arch=('x86_64')
url="https://github.com/covarianttensor/CasterSoundboard"
license=('LGPL-3.0-or-later')
depends=(
    'qt6-base'
    'qt6-declarative'
    'qt6-multimedia'
    'ffmpeg'
    'pipewire'
)
optdepends=(
    'pulseaudio-utils: pactl support for virtual sink/source management'
)
provides=('castersoundboard')
conflicts=('castersoundboard-bin' 'castersoundboard-git')
source=("${TARBALL}")
sha256sums=('${TAR_SHA256}')

build() {
    cmake -B build -S "\${pkgname}-\${pkgver}" \\
        -DCMAKE_BUILD_TYPE=Release \\
        -DCMAKE_INSTALL_PREFIX=/usr \\
        -DBUILD_TESTING=OFF
    cmake --build build -j\$(nproc)
}

package() {
    DESTDIR="\${pkgdir}" cmake --install build
}
EOF

makepkg -f --nodeps

shopt -s nullglob
pkg_files=( "${BUILD_DIR}"/*.pkg.tar.zst )
if [ ${#pkg_files[@]} -gt 0 ]; then
    for pkg in "${pkg_files[@]}"; do
        dest="${REPO_ROOT}/$(basename "${pkg}")"
        mv -f "${pkg}" "${dest}"
        echo "Arch Linux package generated: ${dest}"
    done
else
    echo "Error: No .pkg.tar.zst package was generated by makepkg" >&2
    exit 1
fi
