#!/usr/bin/env bash
set -euo pipefail

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"

# Extract version from CASTER_VERSION, git tag, or VERSION file fallback
FALLBACK_VER="$(cat "${REPO_ROOT}/VERSION" 2>/dev/null || echo "0.0.0")"
VERSION="${CASTER_VERSION:-}"
if [ -z "${VERSION}" ]; then
    if [ -n "${GITHUB_REF_NAME:-}" ]; then
        VERSION="${GITHUB_REF_NAME#v}"
    else
        VERSION="$(git describe --tags --always --dirty 2>/dev/null | sed 's/^v//' || echo "${FALLBACK_VER}-dev")"
    fi
fi
export VERSION

echo "Building Caster Soundboard Snap package version: ${VERSION}"

if ! command -v snapcraft >/dev/null 2>&1; then
    echo "Error: snapcraft is not installed on this host." >&2
    echo "On Ubuntu/Debian: sudo snap install snapcraft --classic" >&2
    echo "Or run the automated GitHub Actions CI workflow: .github/workflows/build-and-release.yml" >&2
    exit 1
fi

cd "${REPO_ROOT}"
snapcraft pack "$@"

shopt -s nullglob
snap_files=( "${REPO_ROOT}"/castersoundboard_*.snap )
if [ ${#snap_files[@]} -gt 0 ]; then
    for snap in "${snap_files[@]}"; do
        echo "Snap package generated: ${snap}"
    done
else
    echo "Error: No .snap package was generated by snapcraft" >&2
    exit 1
fi
